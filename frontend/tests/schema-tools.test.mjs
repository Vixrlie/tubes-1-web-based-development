import test from 'node:test'
import assert from 'node:assert/strict'
import { comparisonDraft, compareSnapshots, createMockSchemaTools, quoteIdentifier } from '../src/features/migrations/schema-tools-source.ts'
import { validateDraft } from '../src/features/migrations/draft-source.ts'

const signal = () => new AbortController().signal
test('schema comparison uses existing table fixtures and generates reversible additive SQL with deferred FKs', async () => {
  const comparison = await createMockSchemaTools('ready', 'ready', 0).compare('mock-shop', 'mock-analytics', signal())
  assert.equal(comparison.target.name, 'shop_db')
  assert.equal(comparison.reference.name, 'analytics_db')
  assert.ok(comparison.changes.some(change => change.table === 'public.events' && change.kind === 'table-added'))
  assert.ok(comparison.changes.some(change => change.table === 'public.products' && change.kind === 'table-removed'))
  const draft = comparisonDraft(comparison, comparison.changes.filter(change => change.supported && !change.destructive).map(change => change.id))
  assert.deepEqual(validateDraft(draft), {})
  assert.equal(draft.irreversible, false)
  assert.ok(draft.sqlUp.indexOf('CREATE TABLE "public"."event_types"') < draft.sqlUp.indexOf('ADD CONSTRAINT "events_type_id_fkey"'))
  assert.ok(draft.sqlDown.indexOf('DROP CONSTRAINT') < draft.sqlDown.indexOf('DROP TABLE'))
  assert.doesNotMatch(draft.sqlUp, /DROP TABLE/)
  assert.match(draft.sqlUp, /GENERATED BY DEFAULT AS IDENTITY/)
})
test('manual backfill/constraint changes are not selectable; deleting data makes the generated draft irreversible', async () => {
  const comparison = await createMockSchemaTools('ready', 'ready', 0).compare('mock-shop', 'mock-analytics', signal())
  const username = comparison.changes.find(change => change.column === 'username')
  assert.equal(username.supported, false)
  assert.throws(() => comparisonDraft(comparison, [username.id]), /didukung/)
  const removed = comparison.changes.find(change => change.table === 'public.orders' && change.kind === 'table-removed')
  assert.equal(removed.supported, true)
  const draft = comparisonDraft(comparison, [removed.id])
  assert.equal(draft.irreversible, true)
  assert.equal(draft.sqlDown, '')
  assert.match(draft.sqlUp, /DROP TABLE "public"\."orders"/)
  assert.throws(() => comparisonDraft(comparison, ['stale-selection']), /didukung/)
  assert.throws(() => comparisonDraft(comparison, []), /didukung/)
})
test('comparison requires both connections and every selected FK dependency; same schema is empty', async () => {
  const source = createMockSchemaTools('ready', 'ready', 0)
  const comparison = await source.compare('mock-shop', 'mock-analytics', signal())
  const events = comparison.changes.find(change => change.table === 'public.events' && change.kind === 'table-added')
  assert.throws(() => comparisonDraft(comparison, [events.id]), /foreign key/)
  assert.deepEqual(compareSnapshots(comparison.target, structuredClone(comparison.target)).changes, [])
  await assert.rejects(source.compare('mock-shop', 'mock-shop', signal()), /berbeda/)
  await assert.rejects(source.compare('mock-shop', 'unknown', signal()), error => error.code === 'not-found')
  await assert.rejects(source.compare('mock-shop', 'mock-hr', signal()), error => error.code === 'unavailable')
  await assert.rejects(createMockSchemaTools('denied', 'ready', 0).compare('mock-shop', 'mock-analytics', signal()), error => error.code === 'denied')
})
test('quote escaping, fixture mutation isolation, empty and error scenarios remain explicit', async () => {
  assert.equal(quoteIdentifier('strange"name'), '"strange""name"')
  const source = createMockSchemaTools('ready', 'ready', 0)
  const a = await source.compare('mock-shop', 'mock-analytics', signal())
  a.target.tables[0].description.columns[0].name = 'changed'
  assert.notEqual((await source.compare('mock-shop', 'mock-analytics', signal())).target.tables[0].description.columns[0].name, 'changed')
  const empty = await createMockSchemaTools('ready', 'empty', 0).compare('mock-shop', 'mock-analytics', signal())
  assert.equal(empty.reference.id, 'mock-analytics')
  assert.deepEqual(empty.changes, [])
  await assert.rejects(createMockSchemaTools('ready', 'error', 0).compare('mock-shop', 'mock-analytics', signal()), /belum dapat/)
})
test('EXPLAIN returns scoped fixture rows/cost, ANALYZE needs edit and DDL is not given a fabricated plan', async () => {
  const source = createMockSchemaTools('ready', 'ready', 0)
  const result = await source.explain('mock-shop', 'SELECT * FROM public.users;', false, signal())
  assert.equal(result.scan.relation, 'public.users')
  assert.equal(result.scan.rows, 1250)
  assert.ok(result.scan.totalCost > result.scan.startupCost)
  assert.equal(result.executionMs, undefined)
  const analyzed = await source.explain('mock-shop', 'SELECT * FROM public.users;', true, signal())
  assert.ok(analyzed.executionMs > 0)
  assert.equal((await source.explain('mock-analytics', 'SELECT * FROM public.users;', false, signal())).scan.rows, 17)
  await assert.rejects(source.explain('mock-shop', 'ALTER TABLE users ADD COLUMN x TEXT;', false, signal()), /DDL/)
  await assert.rejects(source.explain('mock-shop', 'SELECT * FROM public.unknown;', false, signal()), /tabel/)
  await assert.rejects(createMockSchemaTools('readonly', 'ready', 0).explain('mock-shop', 'SELECT * FROM public.users;', true, signal()), /akses Edit/)
  assert.ok(await createMockSchemaTools('readonly', 'ready', 0).explain('mock-shop', 'SELECT * FROM public.users;', false, signal()))
})
test('schema tools cancel before returning a stale comparison or execution plan', async () => {
  const controller = new AbortController()
  const source = createMockSchemaTools('ready', 'ready', 20)
  const pending = source.compare('mock-shop', 'mock-analytics', controller.signal)
  controller.abort()
  await assert.rejects(pending, { name: 'AbortError' })
  await assert.rejects(source.explain('mock-shop', 'SELECT * FROM users;', false, controller.signal), { name: 'AbortError' })
})
